import Foundation

// App-owned ceremony value types for the remote passkey coordinator (remote passkey unlock,
// Step 2). These are the Swift-level contract between the `@MainActor` coordinator and its callers
// (the MCP tool provider in Step 2d and the Settings UI in Step 2e). Nothing here is on the wire
// shape itself — the provider maps these to/from JSON.

/// Which WebAuthn ceremony a challenge belongs to. One pending challenge is kept per
/// `(deviceID, kind)`; a new `begin` for the same pair replaces the previous one.
enum RemotePasskeyCeremonyKind: Hashable {
    case registration
    case assertion
}

/// Binding supplied to a `begin` call. The coordinator mints the `ceremonyID` and returns it in the
/// options; the caller echoes it back in `RemotePasskeyCeremonyContext` at `complete`.
struct RemotePasskeyBeginContext: Equatable {
    let deviceID: String
    let connectionGeneration: UInt64
    let principalConnectionID: String
}

/// Everything the coordinator needs to bind a ceremony to the authenticated connection. The
/// `deviceID` and `principalConnectionID` are supplied by the gateway from the authenticated
/// connection — never from phone-controlled arguments. `connectionGeneration` lets a reconnect
/// invalidate an in-flight ceremony.
struct RemotePasskeyCeremonyContext: Equatable {
    let deviceID: String
    /// 16...64 base64url characters, generated by the coordinator at `begin` and echoed back by
    /// the caller at `complete`.
    let ceremonyID: String
    let connectionGeneration: UInt64
    let principalConnectionID: String
}

/// `navigator.credentials.create()` options the coordinator hands back from `registerBegin`. The
/// provider serializes these to the phone. All security-relevant values originate here.
struct RemotePasskeyRegistrationOptions: Equatable {
    let ceremonyID: String
    /// Base64url challenge (no padding).
    let challengeBase64URL: String
    let relyingPartyID: String
    let relyingPartyName: String
    /// Base64url random user handle.
    let userHandleBase64URL: String
    let userName: String
    let userDisplayName: String
    /// Enrollment window / challenge validity in milliseconds (for the authenticator `timeout`).
    let timeoutMilliseconds: Int
}

/// `navigator.credentials.get()` options the coordinator hands back from `unlockBegin`.
struct RemotePasskeyAssertionOptions: Equatable {
    let ceremonyID: String
    let challengeBase64URL: String
    let relyingPartyID: String
    /// Base64url credential ID to place in `allowCredentials`.
    let allowedCredentialBase64URL: String
    let timeoutMilliseconds: Int
}

/// Result of a verified registration. Registration NEVER grants access.
struct RemotePasskeyRegistrationOutcome: Equatable {
    let deviceID: String
    let epoch: UInt64
    let ceremonyID: String
    let connectionGeneration: UInt64
}

/// Result of a verified unlock assertion. The coordinator does not persist a grant or write disk;
/// the gateway issues the actual access grant in Step 3 from this verified fact.
struct RemotePasskeyUnlockOutcome: Equatable {
    let deviceID: String
    let epoch: UInt64
    let ceremonyID: String
    let connectionGeneration: UInt64
}

/// Typed, generic failures. `challengeInvalid` deliberately covers expired, replayed, mismatched
/// and unknown challenges alike so a response reveals nothing about which guard failed.
enum RemotePasskeyFailure: Error, Equatable {
    case unknownDevice
    case deviceRevoked
    case passkeyNotRequired
    case passkeyNotEnrolled
    case passkeyAlreadyEnrolled
    case enrollmentClosed
    case gatewayUnavailable
    case challengeInvalid
    case verificationFailed
    case originUnavailable
    case reenrollmentRequired
    case policyChanged
    case gatewayUnsupported
    case storageFailed
    case staleAcknowledgment

    /// Stable, generic wire code. Never leaks which specific guard rejected the ceremony.
    var code: String {
        switch self {
        case .unknownDevice: "unknown_device"
        case .deviceRevoked: "device_revoked"
        case .passkeyNotRequired: "passkey_not_required"
        case .passkeyNotEnrolled: "passkey_not_enrolled"
        case .passkeyAlreadyEnrolled: "passkey_already_enrolled"
        case .enrollmentClosed: "enrollment_closed"
        case .gatewayUnavailable: "gateway_unavailable"
        case .challengeInvalid: "challenge_invalid"
        case .verificationFailed: "verification_failed"
        case .originUnavailable: "origin_unavailable"
        case .reenrollmentRequired: "reenrollment_required"
        case .policyChanged: "policy_changed"
        case .gatewayUnsupported: "gateway_unsupported"
        case .storageFailed: "storage_failed"
        case .staleAcknowledgment: "stale_acknowledgment"
        }
    }
}

/// Settings-facing status for one device: the durable (saved) policy state and the separate
/// observed enforcement state. The two are intentionally decoupled — a saved `required` state is
/// not "active" until a compatible gateway acknowledges it (Step 3).
struct RemotePasskeyDeviceStatus: Equatable {
    enum Persisted: Equatable {
        case off
        case requiredNotEnrolled
        case requiredEnrolled
        case requiredNeedsReenrollment
    }

    enum Enforcement: Equatable {
        case gatewayUnavailable
        case gatewayLacksSupport
        case pending
        case applied
    }

    let persisted: Persisted
    let enforcement: Enforcement
    /// Display-only wall-clock deadline derived from the monotonic enrollment window, when open.
    let enrollmentOpenUntil: Date?
    /// Non-nil when Enable cannot proceed, with a user-facing reason.
    let enableBlockedReason: String?
}
